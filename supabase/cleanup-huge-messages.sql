-- ============================================================
-- Yumitask — чистка гигантских сообщений в чате.
-- Картинки хранились как base64 прямо в text и раздували БД,
-- из-за чего запросы к messages висли (чат «бесконечно грузился»).
-- Выполните в Supabase SQL Editor. Обрезает ТОЛЬКО очень длинные
-- сообщения (>150 000 символов), оставляя короткие тексты как есть.
-- ============================================================

update public.messages
set text = case
  when text like 'IMG:%' then left(text, 150000)
  when text like 'FILE:%' then left(text, 150000)
  else text
end
where length(text) > 150000;